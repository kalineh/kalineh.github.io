#!/usr/bin/env python3
"""Generate short-link redirect pages from links.json.
Each key becomes /<key>/index.html that forwards to its URL.
Edit links.json, run `python3 build_links.py`, commit and push.

Safety: real site folders (ja, img, ...) are reserved and can't be used as
link keys, and stale link folders are only removed if this script generated
them (listed in .generated.json AND containing nothing but our redirect page)."""
import json, os, html, shutil, sys

RESERVED = {"ja", "zh", "en", "img", "assets", ".git", "ashigaru", "dragonwake", "solspire", "azemar"}
MARKER = "<!-- generated by build_links.py -->"

links = json.load(open("links.json"))
bad = sorted(k for k in links if k in RESERVED or "/" in k or k.startswith("."))
if bad:
    sys.exit(f"refusing reserved/invalid link keys: {bad}")

def is_ours(d):
    p = os.path.join(d, "index.html")
    if not os.path.isdir(d) or os.listdir(d) != ["index.html"]:
        return False
    txt = open(p, encoding="utf-8").read()
    return MARKER in txt or ('http-equiv="refresh"' in txt and "<title>kalin.games/" in txt)

previous = json.load(open(".generated.json")) if os.path.exists(".generated.json") else []
for d in previous:
    if d in links or d in RESERVED:
        continue
    if is_ours(d):
        shutil.rmtree(d)
    elif os.path.exists(d):
        print(f"skipping {d}/: not a folder this script generated")

for key, url in links.items():
    if os.path.isdir(key) and key not in previous and not is_ours(key):
        sys.exit(f"refusing to overwrite existing folder {key}/ (not generated by build_links.py)")
    os.makedirs(key, exist_ok=True)
    u = html.escape(url, quote=True)
    with open(os.path.join(key, "index.html"), "w") as f:
        f.write(f'''<!doctype html><html><head><meta charset="utf-8">
{MARKER}
<title>kalin.games/{key}</title>
<link rel="canonical" href="{u}"><meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url={u}">
<script>location.replace({json.dumps(url)})</script></head>
<body><p>Redirecting to <a href="{u}">{u}</a></p></body></html>
''')
json.dump(sorted(links), open(".generated.json", "w"))
print("built", len(links), "links")
